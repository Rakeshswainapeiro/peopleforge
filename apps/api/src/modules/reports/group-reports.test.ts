/** Three months of a quarter, with its end and the previous quarter's end. */
function quarter(): SpanInput {
  return {
    months: [
      overviewFixture({ period: '2026-07', headcount: 18, joiners: 1, leavers: 0 }),
      overviewFixture({ period: '2026-08', headcount: 19, joiners: 1, leavers: 0 }),
      overviewFixture({ period: '2026-09' }),
    ],
    end: executiveFixture(),
    previousEnd: executiveFixture({
      period: '2026-06',
      headcount: 16,
      byEntity: [
        {
          entity: { id: '00000000-0000-4000-8000-0000000e000a', code: 'SUB-A' },
          headcount: 16,
          payroll: { AED: '140000.00', EUR: '1000.00' },
          openFlags: 0,
          missing: false,
        },
      ],
    }),
  };
}

describe('turnover and payroll over a span', () => {
  it('measures turnover over the average headcount of its ends', () => {
    expect(spanTurnover(2, 18, 22)).toBe('10.0');
    // Without a start (no data then), the end stands for both.
    expect(spanTurnover(2, null, 20)).toBe('10.0');
    expect(spanTurnover(0, 0, 0)).toBeNull();
  });

  it('adds payroll per currency over subsidiaries, never across currencies', () => {
    expect(groupPayroll(executiveFixture())).toEqual({ AED: '210000.50', USD: '6000.00' });
    expect(groupPayroll(executiveFixture({ byEntity: [] }))).toEqual({});
  });
});

describe('RP-06 Quarterly group HR review [R2-07]', () => {
  it('sums the quarter’s movements and compares payroll with the quarter before', () => {
    const report = rp06('2026-Q3', quarter(), context);
    expect(report).toMatchObject({ code: 'RP-06', period: 'Q3 2026' });
    expect(figures(report)).toEqual([
      'Headcount at quarter end: 20 (16 the period before)',
      'Joiners in the quarter: 5',
      'Leavers in the quarter: 1',
      // 1 leaver over the average of 16 and 20.
      'Quarterly turnover: 5.6% (Leavers over average headcount)',
      'Female share: 45%',
      'Open data flags: 2',
    ]);
    expect(rows(report, 'Month by month')).toEqual([
      ['July 2026', '18', '1', '0'],
      ['August 2026', '19', '1', '0'],
      ['September 2026', '20', '3', '1'],
    ]);
    expect(
      rows(report, 'Monthly payroll at quarter end').map((row) =>
        row.map((cell) => cell.replace(/\s/gu, ' ')),
      ),
    ).toEqual([
      ['AED', 'AED 210,000.50', 'AED 140,000', '+50%'],
      ['EUR', '—', 'EUR 1,000', '—'],
      ['USD', 'USD 6,000', '—', '—'],
    ]);
    // Joiners and leavers per subsidiary over the three months.
    expect(
      rows(report, 'By subsidiary').map((row) => row.map((cell) => cell.replace(/\s/gu, ' '))),
    ).toEqual([
      ['SUB-A', '15', '6', '3', 'AED 150,000.50 · USD 6,000', '2'],
      ['SUB-B', '5', '3', '0', 'AED 60,000', '0'],
    ]);
  });

  it('words a subsidiary without data, and a quarter with no data before', () => {
    const span = quarter();
    const report = rp06(
      '2026-Q3',
      {
        ...span,
        end: executiveFixture({
          byEntity: [
            {
              entity: { id: '00000000-0000-4000-8000-0000000e000b', code: 'SUB-B' },
              headcount: 0,
              payroll: {},
              openFlags: 0,
              missing: true,
            },
          ],
        }),
        previousEnd: executiveFixture({ entitiesWithData: 0, byEntity: [] }),
      },
      context,
    );
    expect(figures(report)[0]).toBe('Headcount at quarter end: 20');
    expect(rows(report, 'By subsidiary')).toEqual([['SUB-B', '0', '3', '0', '—', '0']]);
  });
});

